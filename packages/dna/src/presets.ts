const PRESETS_BY_ID = new Map<string, DNAPreset>(DNA_PRESETS.map((p) => [p.id, p]));

/**
 * Retrieves a Design DNA preset by its identifier.
 */
export function getDNAPreset(id: string): DNAPreset | undefined {
  return PRESETS_BY_ID.get(id);
}

/**
 * Retrieves all registered Design DNA presets.
 */
export function getAllDNAPresets(): readonly DNAPreset[] {
  return DNA_PRESETS;
}

/**
 * Finds presets matching an archetype or search query.
 */
export function findDNAPresets(query: string): DNAPreset[] {
  const q = query.toLowerCase().trim();
  if (!q) return DNA_PRESETS;
  return DNA_PRESETS.filter(
    (p) =>
      p.id.toLowerCase().includes(q) ||
      p.name.toLowerCase().includes(q) ||
      p.description.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      p.dna.primaryArchetype.toLowerCase().includes(q)
  );
}
