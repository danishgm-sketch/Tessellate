/**
 * Retrieves a semantic palette by its identifier.
 */
export function getPalette(id: string): SemanticPalette | undefined {
  return PALETTES_BY_ID.get(id);
}

export const getSemanticPalette = getPalette;

/**
 * Retrieves all registered semantic palettes.
 */
export function getAllPalettes(): readonly SemanticPalette[] {
  return SEMANTIC_PALETTES;
}
