import type { ProjectManifest } from '@tessellate/schemas';
import { normalizeDesignTokens } from '@tessellate/renderer';

function fontFamilyNames(value: string): string[] {
  const names: string[] = [];
  let current = '';
  let quote: '"' | "'" | null = null;
  let escaped = false;

  for (const character of value) {
    if (escaped) {
      current += character;
      escaped = false;
      continue;
    }
    if (quote && character === '\\') {
      escaped = true;
      continue;
    }
    if (quote) {
      if (character === quote) quote = null;
      else current += character;
      continue;
    }
    if ((character === '"' || character === "'") && current.trim() === '') {
      quote = character;
      continue;
    }
    if (character === ',') {
      const name = current.trim();
      if (name) names.push(name);
      current = '';
      continue;
    }
    current += character;
  }

  if (escaped) current += '\\';
  const finalName = current.trim();
  if (finalName) names.push(finalName);
  return names;
}

/**
 * Generates DTCG tokens plus a Style Dictionary CSS build configuration.
 * Style Dictionary is the verified downstream consumer; other design-tool
 * importers have not been certified.
 */
export function generateW3cTokensTree(manifest: ProjectManifest): Record<string, string> {
  const norm = normalizeDesignTokens(manifest.designDNA);
  const files: Record<string, string> = {};

  const tokens = {
    $name: manifest.name,
    $description: `W3C Design Tokens exported from Tessellate for ${manifest.name}`,
    color: {
      accent: {
        primary: {
          $type: 'color',
          $value: norm.colors.accent,
          $description: 'Primary brand accent color',
        },
        hover: {
          $type: 'color',
          $value: norm.colors.accentHover,
          $description: 'Accent hover color',
        },
        soft: {
          $type: 'color',
          $value: norm.colors.accentSoft,
          $description: 'Accent subtle tint',
        },
      },
      surface: {
        primary: {
          $type: 'color',
          $value: norm.colors.canvas,
          $description: 'Base canvas background',
        },
        raised: {
          $type: 'color',
          $value: norm.colors.surfaceRaised,
          $description: 'Elevated card surface',
        },
        base: {
          $type: 'color',
          $value: norm.colors.surface,
          $description: 'Standard card surface',
        },
      },
      text: {
        primary: {
          $type: 'color',
          $value: norm.colors.textPrimary,
          $description: 'Primary text content',
        },
        secondary: {
          $type: 'color',
          $value: norm.colors.textSecondary,
          $description: 'Secondary text and labels',
        },
        muted: {
          $type: 'color',
          $value: norm.colors.textMuted,
          $description: 'Subtle captions and timestamps',
        },
      },
      border: {
        default: {
          $type: 'color',
          $value: norm.colors.border,
          $description: 'Dividers and default borders',
        },
        strong: {
          $type: 'color',
          $value: norm.colors.borderStrong,
          $description: 'High contrast borders',
        },
      },
    },
    dimension: {
      radius: {
        sm: { $type: 'dimension', $value: norm.radius.sm },
        md: { $type: 'dimension', $value: norm.radius.md },
        lg: { $type: 'dimension', $value: norm.radius.lg },
        full: { $type: 'dimension', $value: norm.radius.full },
      },
      spacing: {
        unit: { $type: 'dimension', $value: `${norm.spacing.baseUnit}px` },
        gutter: { $type: 'dimension', $value: norm.spacing.gutterDesktop },
      },
    },
    typography: {
      fontFamily: {
        display: { $type: 'fontFamily', $value: fontFamilyNames(norm.typography.displayFont) },
        heading: { $type: 'fontFamily', $value: fontFamilyNames(norm.typography.headingFont) },
        body: { $type: 'fontFamily', $value: fontFamilyNames(norm.typography.bodyFont) },
        mono: { $type: 'fontFamily', $value: fontFamilyNames(norm.typography.monoFont) },
      },
    },
  };

  files['tokens.json'] = JSON.stringify(tokens, null, 2);
  files['config.json'] = JSON.stringify(
    {
      usesDtcg: true,
      source: ['tokens.json'],
      platforms: {
        css: {
          transformGroup: 'css',
          buildPath: 'build/css/',
          files: [{ destination: 'tokens.css', format: 'css/variables' }],
        },
      },
    },
    null,
    2
  );
  files['README.md'] = `# Design Tokens: ${manifest.name}

Generated by [Tessellate](https://github.com/danishgm-sketch/Tessellate).
Format: W3C Design Tokens Community Group specification.

## Style Dictionary consumer check

- Install Style Dictionary in this folder and build the CSS variables:
  \`\`\`bash
  npx style-dictionary build
  \`\`\`

This package includes \`config.json\` for that build. It exports CSS variables
from \`tokens.json\`; it does not provide direct-import certification for Figma
or Penpot.
`;

  return files;
}
