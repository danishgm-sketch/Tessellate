export interface InitOptions {
  cwd?: string;
  componentsDir?: string;
  tokensPath?: string;
  yes?: boolean;
}

export async function runInit(options: InitOptions = {}) {
  const cwd = path.resolve(options.cwd || process.cwd());
  const existingConfig = loadConfig(cwd);

  const config = {
    ...existingConfig,
    componentsDir: options.componentsDir || existingConfig.componentsDir || DEFAULT_CONFIG.componentsDir,
    tokensPath: options.tokensPath || existingConfig.tokensPath || DEFAULT_CONFIG.tokensPath,
  };

  const configPath = saveConfig(config, cwd);
  console.log(`[tess] Initialized Tessellate configuration at: ${configPath}`);

  // Create components directory if not present
  const fullComponentsDir = path.join(cwd, config.componentsDir);
  if (!fs.existsSync(fullComponentsDir)) {
    fs.mkdirSync(fullComponentsDir, { recursive: true });
    console.log(`[tess] Created components directory: ${fullComponentsDir}`);
  }

  // Create tokens CSS if not present
  const fullTokensPath = path.join(cwd, config.tokensPath);
  const tokensDir = path.dirname(fullTokensPath);
  if (!fs.existsSync(tokensDir)) {
    fs.mkdirSync(tokensDir, { recursive: true });
  }

  if (!fs.existsSync(fullTokensPath)) {
    fs.writeFileSync(fullTokensPath, INITIAL_TOKENS_CSS, 'utf-8');
    console.log(`[tess] Created semantic tokens stylesheet: ${fullTokensPath}`);
  }

  console.log('[tess] Ready! Add components with: tess add <resource-slug>');
  return { configPath, tokensPath: fullTokensPath, componentsDir: fullComponentsDir };
}
