import React, { useEffect, useRef, useState } from 'react';

export type AIChatPanelVariant = 'quiet' | 'expressive' | 'nocturne';

export interface AIChatPanelProps {
  variant?: AIChatPanelVariant;
}

export function AIChatPanel({ variant = 'quiet' }: AIChatPanelProps) {
  const inputRef = useRef<HTMLInputElement>(null);
  const messagesRef = useRef<HTMLDivElement>(null);
  const [messages, setMessages] = useState([
    { role: 'user', content: 'How could we make the onboarding steps easier to follow?' },
    {
      role: 'assistant',
      content:
        'Example reply: group related steps and show progress. This sample is not generated by a model.',
    },
  ]);

  useEffect(() => {
    const messageList = messagesRef.current;
    if (messageList) messageList.scrollTop = messageList.scrollHeight;
  }, [messages]);

  const cardBg =
    variant === 'nocturne'
      ? 'bg-[#0B0D10] border-[#2E3440] text-white'
      : variant === 'expressive'
        ? 'bg-white border-[#D9D6CF] text-neutral-900 shadow-sm'
        : 'bg-white border-neutral-200 text-neutral-900';

  const userBubble =
    variant === 'nocturne'
      ? 'bg-[#151921] border-[#2E3440] text-neutral-200'
      : variant === 'expressive'
        ? 'bg-neutral-100 border-neutral-200 text-neutral-900'
        : 'bg-neutral-50 border-neutral-200 text-neutral-900';

  const assistantBubble =
    variant === 'nocturne'
      ? 'bg-[#0F141C] border-cyan-900/50 text-cyan-50'
      : variant === 'expressive'
        ? 'bg-blue-50/50 border-blue-200 text-neutral-900'
        : 'bg-white border-neutral-200 text-neutral-900';

  const sendBtn =
    variant === 'nocturne'
      ? 'bg-cyan-500 text-black font-semibold hover:bg-cyan-400'
      : variant === 'expressive'
        ? 'bg-[#2547E8] text-white font-medium hover:bg-blue-700'
        : 'bg-neutral-900 text-white dark:bg-white dark:text-neutral-900 hover:opacity-90';

  const sendExample = () => {
    const message = inputRef.current?.value.trim() ?? '';
    if (!message) return;
    setMessages((prev) => [
      ...prev,
      { role: 'user', content: message },
      { role: 'assistant', content: 'Example response: This preview does not connect to a model.' },
    ]);
    if (inputRef.current) inputRef.current.value = '';
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    sendExample();
  };

  return (
    <div
      className={`w-full h-[min(420px,80vh)] min-h-0 p-6 rounded-xl border flex flex-col overflow-hidden transition-colors ${cardBg}`}
    >
      <div className="flex items-center justify-between pb-4 border-b border-neutral-100 dark:border-neutral-800">
        <div className="flex items-center gap-2.5">
          <h2 className="text-sm font-semibold tracking-tight">Example assistant conversation</h2>
        </div>
      </div>

      <p className="pt-3 text-xs text-neutral-500 dark:text-neutral-400">
        Example conversation. This preview does not connect to a model; sending adds a fixed local
        example reply.
      </p>

      <div ref={messagesRef} className="flex-1 min-h-0 py-4 space-y-4 overflow-y-auto">
        {messages.map((m, idx) => (
          <div
            key={idx}
            className={`flex flex-col ${m.role === 'user' ? 'items-end' : 'items-start'}`}
          >
            <div className="text-[10px] uppercase font-mono text-neutral-400 mb-1 px-1">
              {m.role === 'user' ? 'You' : 'Assistant'}
            </div>
            <div
              className={`p-3.5 rounded-xl text-xs max-w-lg border leading-relaxed ${
                m.role === 'user' ? userBubble : assistantBubble
              }`}
            >
              {m.content}
            </div>
          </div>
        ))}
      </div>

      <form
        onSubmit={handleSubmit}
        className="flex gap-2 pt-3 border-t border-neutral-100 dark:border-neutral-800"
      >
        <input
          type="text"
          ref={inputRef}
          onKeyDown={(event) => {
            if (event.key === 'Enter' && !event.nativeEvent.isComposing) {
              event.preventDefault();
              sendExample();
            }
          }}
          aria-label="Message to the example assistant"
          placeholder="Type an example message..."
          className="flex-1 px-3.5 py-2 text-xs rounded-lg border border-neutral-200 dark:border-neutral-800 bg-transparent focus:outline-none focus:ring-1 focus:ring-neutral-400"
        />
        <button
          type="button"
          onClick={sendExample}
          className={`px-4 py-2 text-xs rounded-lg transition-colors ${sendBtn}`}
        >
          Send example
        </button>
      </form>
    </div>
  );
}
