import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve('quality/evidence/step-45/public-v53-reaudit-2026-10-28');
const site='https://tessellate-v1-review.ismayildanish-gm.chatgpt.site';
await mkdir(path.join(root,'interactive'),{recursive:true});
const browser=await chromium.launch({headless:true});
const results=[];
for(const vp of [{name:'desktop-1440x900',width:1440,height:900},{name:'mobile-390x844',width:390,height:844}]){
 const context=await browser.newContext({viewport:{width:vp.width,height:vp.height},isMobile:vp.width<500,hasTouch:vp.width<500,reducedMotion:'reduce'});
 const page=await context.newPage(); const runtime={console:[],pageErrors:[],failedRequests:[],badResponses:[]};
 page.on('console',m=>{if(m.type()==='error'||m.type()==='warning')runtime.console.push({type:m.type(),text:m.text()});});
 page.on('pageerror',e=>runtime.pageErrors.push(e.message));
 page.on('requestfailed',r=>runtime.failedRequests.push({url:r.url(),error:r.failure()?.errorText??'unknown'}));
 page.on('response',r=>{if(r.status()>=400)runtime.badResponses.push({url:r.url(),status:r.status()});});
 const showcaseResponse=await page.goto(site+'/showcase/showcase-playful-hr/',{waitUntil:'domcontentloaded'});
 await page.getByRole('heading',{name:'Kudos Employee Experience'}).waitFor({state:'visible'});
 const headings=await page.locator('main h1, main h2').allTextContents();
 const h1=await page.locator('main h1').first().innerText();
 const cta=page.locator('main h2').last();
 await cta.scrollIntoViewIfNeeded();
 await cta.locator('xpath=ancestor::section[1]').screenshot({path:path.join(root,'interactive',`showcase-cta-after-${vp.name}.png`)});
 const showcase={status:showcaseResponse?.status()??null,route:page.url(),h1,headings,ctaHeading:await cta.innerText(),heroHeadingOccurrences:headings.filter(x=>x.trim()===h1.trim()).length,screenshot:path.relative(process.cwd(),path.join(root,'interactive',`showcase-cta-after-${vp.name}.png`)).replaceAll('\\','/')};
 await page.goto(site+'/tools/section-planner/',{waitUntil:'domcontentloaded'});
 const field=page.getByRole('textbox',{name:'Custom section title'});
 await field.waitFor({state:'visible'});
 const identity=await field.evaluate(e=>({id:e.id,name:e.getAttribute('name'),ariaLabel:e.getAttribute('aria-label')}));
 await field.fill('Employee timeline');
 await page.getByRole('button',{name:/^Add$/}).click();
 await page.getByText('Employee timeline',{exact:true}).waitFor({state:'visible'});
 const sectionScreenshot=path.join(root,'interactive',`section-planner-after-${vp.name}.png`);
 await page.screenshot({path:sectionScreenshot,fullPage:false});
 const planner={status:200,route:page.url(),viewport:{width:vp.width,height:vp.height},identity,added:true,visible:await page.getByText('Employee timeline',{exact:true}).isVisible(),screenshot:path.relative(process.cwd(),sectionScreenshot).replaceAll('\\','/')};
 results.push({viewport:vp.name,showcase,planner,runtime});
 await context.close();
}
await browser.close();
const report={site,siteVersion:53,capturedAt:new Date().toISOString(),results};
await writeFile(path.join(root,'interactive','deployed-fix-verification-v53.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
