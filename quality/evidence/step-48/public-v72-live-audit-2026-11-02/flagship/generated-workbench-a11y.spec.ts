import { test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=dirname(fileURLToPath(import.meta.url));
test('scan generated Direction C Workbench accessibility in deployed runtime',async({page},info)=>{
 test.setTimeout(120000);
 const runtime={consoleErrors:[],consoleWarnings:[],uncaught:[],failedRequests:[],badResponses:[],axeInstrumentationConsole:[]};
 let scanning=false;
 page.on('console',m=>{if(m.type()==='error'){(scanning?runtime.axeInstrumentationConsole:runtime.consoleErrors).push(m.text());}if(m.type()==='warning')runtime.consoleWarnings.push(m.text());});
 page.on('pageerror',e=>runtime.uncaught.push(e.message));
 page.on('requestfailed',r=>runtime.failedRequests.push(`${r.method()} ${r.url()} ${r.failure()?.errorText??''}`));
 page.on('response',r=>{if(r.status()>=400)runtime.badResponses.push({status:r.status(),url:r.url()});});
 const brief='Build a professional but playful employee experience platform for a 500-person technology company. The marketing site should feel warm and energetic, while the application itself should feel professional, fast and trustworthy. Make the dashboard refined, make onboarding playful, keep settings conservative.';
 await page.goto('/compose');
 await page.getByTestId('catalog-status').getByText('Catalogue ready').waitFor({state:'visible'});
 await page.locator('#description').fill(brief);
 await page.locator('#feel').fill('professional but playful');
 await page.getByRole('button',{name:'Refined',exact:true}).click();
 await page.getByRole('button',{name:'Radical',exact:true}).click();
 await page.getByTestId('compose-submit-btn').click();
 await page.getByTestId('direction-card-03').waitFor({state:'visible'});
 await page.getByTestId('open-workbench-dir-03').click();
 await page.waitForURL(/\/workbench\?project=/);
 await page.getByTestId('top-toolbar').waitFor({state:'visible'});
 await page.waitForTimeout(300);
 const project=await page.evaluate(()=>({url:location.href,title:document.title,headings:[...document.querySelectorAll('h1,h2')].map(n=>n.textContent?.trim()).slice(0,8),documentWidth:document.documentElement.scrollWidth,viewportWidth:innerWidth,bodyChars:document.body.innerText.length}));
 const viewport=info.project.name==='mobile-chrome'?'390x844':'1440x900';
 const screenshot=join(root,`generated-workbench-${viewport}.png`);
 await page.screenshot({path:screenshot,fullPage:true});
 scanning=true;
 const axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa']).analyze();
 scanning=false;
 const result={deploymentUrl:page.url().split('#')[0],viewport,project,runtime:{...runtime},axe:{violations:axe.violations.map(v=>({id:v.id,impact:v.impact,description:v.description,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))})),incomplete:axe.incomplete.map(v=>({id:v.id,impact:v.impact,description:v.description,nodes:v.nodes.map(n=>({target:n.target,any:n.any.map(c=>({id:c.id,message:c.message,data:c.data}),),all:n.all.map(c=>({id:c.id,message:c.message,data:c.data})),none:n.none.map(c=>({id:c.id,message:c.message,data:c.data}))}))})),passes:axe.passes.length},screenshot:screenshot.replaceAll('\\','/')};
 await writeFile(join(root,`generated-workbench-${viewport}.json`),JSON.stringify(result,null,2)+'\n');
 console.log(JSON.stringify({viewport,project,axeViolations:axe.violations.map(v=>({id:v.id,impact:v.impact})),incomplete:axe.incomplete.map(v=>v.id),runtime}));
});
